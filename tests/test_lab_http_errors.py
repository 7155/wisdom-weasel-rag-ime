class LabHttpErrorTests(unittest.TestCase):
    def setUp(self) -> None:
        self.readers = {
            key: Mock(return_value={"ok": True, "items": []}) for key in CASES
        }
        agent = SimpleNamespace(
            **{CASES[key][0]: reader for key, reader in self.readers.items()}
        )
        self.service = SimpleNamespace(
            agent=agent, config=SimpleNamespace(server_name="agent gateway")
        )

        class Handler(DebugRequestHandler):
            def log_message(self, _format, *args):
                pass

        Handler.service = self.service
        Handler.static_dir = Path("debug")
        self.server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()
        self.addCleanup(self.server.server_close)
        self.addCleanup(self.thread.join, 2)
        self.addCleanup(self.server.shutdown)

    def get(self, path, *, headers=None):
        request = Request(
            f"http://127.0.0.1:{self.server.server_port}{path}", headers=headers or {}
        )
        try:
            response = urlopen(request, timeout=5)
        except HTTPError as error:
            response = error
        with response:
            self.assertEqual(
                response.headers["Content-Type"], "application/json; charset=utf-8"
            )
            self.assertEqual(response.headers["Cache-Control"], "no-store")
            return response.status, json.loads(response.read())

    def test_success_defaults_and_query_selection(self):
        for key, (_handler, fields) in CASES.items():
            with self.subTest(route=key):
                self.assertEqual(self.get(BASE + key), (200, {"ok": True, "items": []}))
                self.readers[key].assert_called_once_with(dict.fromkeys(fields, ""))
                self.readers[key].reset_mock()
                query = [(field, f"中文-{index}") for index, field in enumerate(fields)]
                query += [(fields[0], "second-value"), ("ignored", "not-forwarded")]
                self.get(BASE + key + "?" + urlencode(query))
                self.readers[key].assert_called_once_with(
                    {field: f"中文-{index}" for index, field in enumerate(fields)}
                )
                descriptor = find_route("GET", BASE + key)
                self.assertFalse(descriptor.remote_safe)
                self.assertEqual(descriptor.aliases, ())
                self.assertEqual(descriptor.contract, "")
                self.assertEqual(descriptor.response_contract, "")

    def test_parameter_storage_and_internal_errors_keep_exact_responses(self):
        private = "/private/paw.sqlite token=do-not-publish"
        for key in CASES:
            failures = (
                (ValueError(private), INVALID[key]),
                (
                    TypeError(private),
                    INVALID[key] if key == "trials" else INTERNAL[key],
                ),
                (OSError(private), STORAGE[key]),
                (sqlite3.OperationalError(private), STORAGE[key]),
                (RuntimeError(private), INTERNAL[key]),
            )
            for failure, expected in failures:
                with self.subTest(route=key, failure=type(failure).__name__):
                    self.readers[key].side_effect = failure
                    self.assertEqual(self.get(BASE + key), expected)

