    def test_auth_and_remote_policy_run_before_lab_error_mapping(self):
        with patch.dict(
            os.environ, {"RAG_IME_REMOTE_ALLOWED_LOGINS": "reader@example.test"}
        ):
            for key in CASES:
                for headers, code in (
                    ({"Host": "paw.example.test"}, "scope_required"),
                    (
                        {
                            "Host": "paw.example.test",
                            "Tailscale-User-Login": "reader@example.test",
                        },
                        "route_not_allowed",
                    ),
                ):
                    with self.subTest(route=key, code=code):
                        status, body = self.get(BASE + key, headers=headers)
                        self.assertEqual(status, 403)
                        self.assertEqual(body["errorCode"], code)
                        self.assertEqual(
                            body["schemaVersion"], "rag-ime.gateway-access.v1"
                        )
                        self.readers[key].assert_not_called()

    def test_new_read_and_alias_use_declared_adapter_without_a_server_branch(self):
        original = find_route("GET", BASE + "trials")
        route = replace(
            original,
            path=BASE + "new-query",
            aliases=(BASE + "new-query-alias",),
            handler="agent.another_lab_read",
        )
        self.service.agent.another_lab_read = Mock(
            side_effect=ValueError("private detail")
        )
        entries = {("GET", path): route for path in (route.path, *route.aliases)}
        with patch.dict(ROUTE_TABLE, entries):
            for path in (route.path, *route.aliases):
                self.assertEqual(self.get(path), INVALID["trials"])

    def test_request_handler_response_validation_order_is_preserved(self):
        for key in CASES:
            original = find_route("GET", BASE + key)
            route = replace(
                original, contract="request.schema", response_contract="response.schema"
            )
            calls = []

            def validate(_payload, contract, recorded=calls):
                recorded.append(contract)

            def read(_payload, recorded=calls):
                recorded.append("handler")
                return {"ok": True}

            self.readers[key].side_effect = read
            with (
                self.subTest(route=key),
                patch.dict(ROUTE_TABLE, {("GET", route.path): route}),
                patch("rag_ime.control_api.dispatch.validate_contract", side_effect=validate),
            ):
                self.assertEqual(self.get(route.path), (200, {"ok": True}))
                self.assertEqual(
                    calls, ["request.schema", "handler", "response.schema"]
                )
            self.readers[key].reset_mock()
            with (
                patch.dict(ROUTE_TABLE, {("GET", route.path): route}),
                patch(
                    "rag_ime.control_api.dispatch.validate_contract",
                    side_effect=ValueError("bad request"),
                ),
            ):
                self.assertEqual(self.get(route.path), INVALID[key])
                self.readers[key].assert_not_called()
            response_only = replace(original, response_contract="response.schema")
            with (
                patch.dict(ROUTE_TABLE, {("GET", route.path): response_only}),
                patch(
                    "rag_ime.control_api.dispatch.validate_contract",
                    side_effect=ValueError("bad response"),
                ),
            ):
                self.assertEqual(self.get(route.path), INVALID[key])
                self.readers[key].assert_called_once()

    def test_error_boundary_includes_transform_and_response_encoding(self):
        for key in CASES:
            original = find_route("GET", BASE + key)
            transform = Mock(side_effect=ValueError("bad transform"))
            route = replace(original, transform=transform)
            with (
                self.subTest(route=key),
                patch.dict(ROUTE_TABLE, {("GET", route.path): route}),
            ):
                self.assertEqual(self.get(route.path), INVALID[key])
                self.readers[key].assert_not_called()
            self.readers[key].return_value = {"unserializable": object()}
            expected = INVALID[key] if key == "trials" else INTERNAL[key]
            self.assertEqual(self.get(original.path), expected)


